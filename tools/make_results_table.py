"""Render saved public metrics; never imports a scorer or opens labels."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("results/metrics.json", "results/p08b_a.json", "results/p08b_b.json", "results/p08b_held_out.json")
METRICS = ("recall_at_K", "hook_hit", "hook_found", "precision_at_10", "negative_hit_rate")
GLANCE_START = "<!-- results-at-a-glance:start -->"
GLANCE_END = "<!-- results-at-a-glance:end -->"


def readme_glance(root=ROOT):
    official, a, b, held = (json.loads((root / source).read_text(encoding="utf-8")) for source in SOURCES)

    def count(row):
        ratio(row)  # Validate saved values before publishing a concise count.
        return f"{row['k']}/{row['n']}"

    lines = [GLANCE_START, "**Results at a glance**",
             f"- Official held-out Recall@{official['counts']['K']}: v1 {count(official['tool']['recall_at_K'])}; baseline {count(official['baseline']['recall_at_K'])}.",
             f"- Official negatives hit: v1 {count(official['tool']['negative_hit_rate'])}; baseline {count(official['baseline']['negative_hit_rate'])}."]
    for label, data in (("A", a), ("B", b)):
        lines.append(f"- Fresh {label}, Recall@{data['K']}: v2 {count(data['systems']['v2']['primary']['recall_at_K'])}; v1 {count(data['systems']['v1']['primary']['recall_at_K'])}.")
    lines.append(f"- Held-out v2 Recall@{held['K']}: {count(held['systems']['v2']['primary']['recall_at_K'])} — post-hoc; [definitions and limits](docs/RESULTS.md).")
    return "\n".join([*lines, GLANCE_END]) + "\n\n"


def update_readme(root=ROOT):
    path = root / "README.md"
    text = path.read_text(encoding="utf-8")
    if text.startswith(GLANCE_START):
        if GLANCE_END not in text:
            raise ValueError("README result markers are incomplete")
        text = text.split(GLANCE_END, 1)[1].lstrip("\n")
    path.write_text(readme_glance(root) + text, encoding="utf-8", newline="\n")


def ratio(row):
    k, n, value = row["k"], row["n"], row["value"]
    if type(k) is not int or type(n) is not int or not 0 <= k <= n:
        raise ValueError("invalid metric counts")
    if n == 0:
        if value is not None:
            raise ValueError("zero-denominator metric must be undefined")
        return "n/a (n=0)"
    if not isinstance(value, (int, float)) or abs(value - k / n) > 1e-10:
        raise ValueError("metric value disagrees with counts")
    text = f"{k}/{n} = {value:.3f}"
    ci = row.get("wilson95")
    if isinstance(ci, list) and len(ci) == 2:
        text += f" [{ci[0]:.3f}, {ci[1]:.3f}]"
    return text


def render(root=ROOT):
    lines = ["# Saved evaluation results", "", "Generated by `python tools/make_results_table.py` from the four public result files. No scoring is performed.", "",
             "Each cell shows matches/denominator and the saved fraction; brackets show saved Wilson 95% intervals where available. Undefined denominators are n/a.", ""]
    for index, source in enumerate(SOURCES):
        raw = (root / source).read_bytes()
        data = json.loads(raw)
        if index == 0:
            title = "P08: official v1 held-out, scored once"
            counts = data["counts"]
            systems = {"v1 official": data["tool"], "baseline official": data["baseline"]}
            paired = {"v1 vs baseline": data["paired_tool_vs_baseline"]}
        else:
            title = {1: "P08b: fresh block A", 2: "P08b: fresh block B", 3: "P08b: held-out v2 — post-hoc (after seeing v1 results)"}[index]
            counts = data
            systems = {name: {**s["primary"], "L_size": s["L_size"], "K_used": s["K_used"]}
                       for name, s in data["systems"].items() if name != "baseline_sensitivity_no_20_60"}
            paired = data["paired"]
        lines.extend([f"## {title}", "", f"Positive gold n={counts['G']}; negative gold n={counts['negatives']}; K={counts['K']}.", "",
                      "| Metric | " + " | ".join(systems) + " |", "|---|" + "---|" * len(systems),
                      "| List size / K used | " + " | ".join(f"{s['L_size']} / {s['K_used']}" for s in systems.values()) + " |"])
        for metric in METRICS:
            lines.append(f"| {metric} | " + " | ".join(ratio(s[metric]) for s in systems.values()) + " |")
        for grade in ("3", "2", "1"):
            lines.append(f"| Recall grade {grade} | " + " | ".join(ratio(s["recall_by_grade"][grade]) for s in systems.values()) + " |")
        lines.extend(["", "Definitions copied from this result:", ""])
        for metric in (*METRICS, "recall_by_grade", "matching"):
            lines.append(f"- **{metric}:** {data['definitions'][metric]}")
        lines.extend(["", "P@10 uses the same top-K matching: positions beyond K cannot add matches even when its denominator is 10.", "",
                      "| Paired comparison | Positive n | First-only / comparator-only | Exact McNemar p | Mean difference [saved bootstrap 95%] |",
                      "|---|---|---|---|---|"])
        for name, row in paired.items():
            mc, bs = row["mcnemar"], row["bootstrap"]
            lines.append(f"| {name} | {row['n']} | {mc['tool_only']} / {mc['baseline_only']} | {mc['p_two_sided']:.6g} | {bs['mean_diff']:.4f} [{bs['ci95'][0]:.3f}, {bs['ci95'][1]:.3f}] |")
        lines.extend(["", "Paired differences are fractions on the positive labels; these small samples do not establish equivalence.", "",
                      f"Source: [{source}](../{source}); SHA-256 `{hashlib.sha256(raw).hexdigest()}`.", ""])
    lines.extend(["## Interpretation limits", "", "A and B are separate blocks; no pooling. B was selected for candidate-set differences and includes pilot-exposed episodes. Gold is incomplete judgement from one labeller who had read the show. The held-out v2 result is post-hoc. Zero discordance or a zero-width bootstrap interval does not prove equivalence.", "",
                  "See [P08](../logs/P08_report.md) and [P08b](../logs/P08b_report.md) for sensitivities, selection history, structural misses and full limitations.", ""])
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.parse_args(argv)
    target = ROOT / "docs/RESULTS.md"
    text = render(ROOT)
    target.parent.mkdir(exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    update_readme(ROOT)
    print("Generated docs/RESULTS.md from 4 saved result files; no scoring.")


if __name__ == "__main__":
    main()
